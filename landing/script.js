let currentLang = localStorage.getItem('dcplatforma_lang') || 'kk';
let currentStep = 0;
const answers = [];

function t(key) {
  return translations[currentLang]?.[key] || translations.kk[key] || key;
}

function toggleLang() {
  currentLang = currentLang === 'kk' ? 'ru' : 'kk';
  localStorage.setItem('dcplatforma_lang', currentLang);
  document.documentElement.lang = currentLang;
  document.getElementById('langToggle').textContent = currentLang === 'kk' ? 'РУС' : 'ҚАЗ';
  applyTranslations();
  if (document.getElementById('s-quiz').classList.contains('active')) {
    renderStep();
  }
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key === 'hidden') return;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = t(key);
    } else {
      el.innerHTML = t(key);
    }
  });
  document.title = t('meta_title');
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute('content', t('meta_desc'));
}

function showScreen(id) {
  document.querySelectorAll('.screen').forEach(s => s.classList.remove('active'));
  const el = document.getElementById(id);
  if (el) el.classList.add('active');
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

function showQuiz() {
  currentStep = 0;
  answers.length = 0;
  showScreen('s-quiz');
  renderStep();
}

const quizOptionKeys = [
  ['quiz_q1_o1', 'quiz_q1_o2', 'quiz_q1_o3', 'quiz_q1_o4'],
  ['quiz_q2_o1', 'quiz_q2_o2', 'quiz_q2_o3', 'quiz_q2_o4'],
  ['quiz_q3_o1', 'quiz_q3_o2', 'quiz_q3_o3', 'quiz_q3_o4'],
  ['quiz_q4_o1', 'quiz_q4_o2', 'quiz_q4_o3', 'quiz_q4_o4']
];
const quizQuestionKeys = ['quiz_q1', 'quiz_q2', 'quiz_q3', 'quiz_q4'];

function renderStep() {
  const container = document.getElementById('q-container');
  const fill = document.getElementById('progressFill');
  const stepLabel = document.getElementById('stepLabel');
  const backBtn = document.getElementById('backBtn');

  const total = 5;
  const percent = ((currentStep + 1) / total) * 100;
  fill.style.width = Math.min(percent, 80) + '%';
  backBtn.style.display = currentStep > 0 ? 'flex' : 'none';

  if (currentStep < 4) {
    stepLabel.textContent = `${currentStep + 1}/4 ${t('step_prefix')}`;

    const qKey = quizQuestionKeys[currentStep];
    const oKeys = quizOptionKeys[currentStep];

    let optsHtml = oKeys.map((ok, i) => `
      <button class="quiz-option" onclick="selectOption(${i})">
        <span>${t(ok)}</span>
      </button>
    `).join('');

    container.innerHTML = `
      <div class="quiz-body">
        <div class="quiz-question">${t(qKey)}</div>
        <div class="quiz-options">${optsHtml}</div>
      </div>
    `;
  } else {
    stepLabel.textContent = `4/4 ${t('step_prefix')}`;
    container.innerHTML = `
      <div class="quiz-body">
        <div class="quiz-question">${t('quiz_form_title')}</div>
        <p style="font-size:0.875rem;color:rgba(255,255,255,0.6);margin-bottom:24px;line-height:1.6">${t('quiz_form_text')}</p>
        <form class="quiz-form" onsubmit="submitForm(event)">
          <input class="quiz-input" type="text" id="nameInput" placeholder="${t('quiz_form_placeholder_name')}" required />
          <input class="quiz-input" type="email" id="emailInput" placeholder="Email" required />
          <input class="quiz-input" type="tel" id="phoneInput" placeholder="${t('quiz_form_placeholder_phone')}" required pattern="[\+\d\s\-\(\)]{7,20}" title="+7 700 000 00 00" oninput="document.getElementById('phoneError').style.display='none';this.classList.remove('error')" />
          <span id="phoneError" style="color:#ef4444;font-size:0.75rem;display:none">Телефон нөмірін дұрыс енгізіңіз (+7 700 000 00 00)</span>
          <button type="submit" class="btn btn-primary btn-full neon-glow">${t('quiz_form_btn')}</button>
        </form>
        <div class="form-note">Деректеріңіз қорғалған</div>
      </div>
    `;
  }
}

function selectOption(index) {
  const keys = quizOptionKeys[currentStep];
  answers[currentStep] = t(keys[index]);
  currentStep++;
  renderStep();
}

function prevStep() {
  if (currentStep > 0) {
    currentStep--;
    renderStep();
  }
}

function sendToTelegram(msg) {
  if (TG_TOKEN.includes('ТОКЕН') || TG_CHAT_ID.includes('CHAT_ID') || TG_CHAT_ID === '0') return;
  const url = `https://api.telegram.org/bot${TG_TOKEN}/sendMessage`;
  const body = { chat_id: TG_CHAT_ID, text: msg, parse_mode: 'HTML' };
  fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })
    .catch(err => console.error('Telegram error:', err));
  console.log('Telegram sent');
}

function submitForm(e) {
  e.preventDefault();
  const name = document.getElementById('nameInput').value.trim();
  const email = document.getElementById('emailInput').value.trim();
  const phone = document.getElementById('phoneInput').value.trim();
  if (!name || !email || !phone) return;

  const phoneClean = phone.replace(/[\s\-\ \(\)]/g, '');
  if (phoneClean.length < 7 || !/^[\+\d]+$/.test(phoneClean)) {
    const phoneInput = document.getElementById('phoneInput');
    const phoneError = document.getElementById('phoneError');
    phoneInput.classList.add('error');
    phoneError.style.display = 'block';
    return;
  }

  const answersText = Object.values(answers).map((a, i) => `  ${i+1}. ${a}`).join('\n');
  const msg = `<b>🔔 Жаңа лид!</b>\n\n<b>Аты:</b> ${name}\n<b>Email:</b> ${email}\n<b>WhatsApp:</b> ${phone}\n<b>Тіл:</b> ${currentLang}\n\n<b>Жауаптар:</b>\n${answersText}\n\n<b>Уақыты:</b> ${new Date().toLocaleString('kk-KZ')}`;

  sendToTelegram(msg);
  console.log('Lead captured:', { name, email, phone, lang: currentLang, answers: { ...answers } });

  showScreen('s-result');
}

function resetQuiz() {
  currentStep = 0;
  answers.length = 0;
  showScreen('s-hero');
}

function initScrollAnimations() {
  const els = document.querySelectorAll('.fade-el');
  els.forEach((el, index) => {
    el.style.transitionDelay = `${(index % 4) * 0.1}s`;
  });

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
      }
    });
  }, { threshold: 0.1 });

  els.forEach(el => observer.observe(el));
}

document.addEventListener('DOMContentLoaded', () => {
  document.documentElement.lang = currentLang;
  const langBtn = document.getElementById('langToggle');
  if (langBtn) langBtn.textContent = currentLang === 'kk' ? 'РУС' : 'ҚАЗ';
  applyTranslations();
  initScrollAnimations();
});
